// Bundles the narrator clips (server/assets/narrator/*.m4a, ~120 KB total) into the TV app as base64 strings, so
// they play offline (Demo party) without reading binary assets from the package at runtime.
// Run: node tv/scripts/bundle-narrator.mjs   (after `cd server && bun run gen:narrator`)
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = join(HERE, '..', '..', 'server', 'assets', 'narrator');
const OUT = join(HERE, '..', 'src', 'assets', 'narrator.ts');
const {clips} = JSON.parse(readFileSync(join(SRC, 'manifest.json'), 'utf8'));
const lines = clips.map((c) => `  '${c.id}': '${readFileSync(join(SRC, c.file)).toString('base64')}',`);
writeFileSync(
  OUT,
  `// Generated by scripts/bundle-narrator.mjs from server/assets/narrator (AAC-LC in fragmented MP4). Do not edit.\n` +
    `export const NARRATOR: Record<string, string> = {\n${lines.join('\n')}\n};\n`,
);
console.log(`wrote ${OUT}: ${clips.map((c) => c.id).join(', ')}`);
