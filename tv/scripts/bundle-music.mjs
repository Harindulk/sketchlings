// Bundles the menu music loop (server/assets/music/menu.m4a, CC0, server/CREDITS.md) into the TV app as base64 strings,
// like bundle-narrator.mjs. Run: node tv/scripts/bundle-music.mjs
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = join(HERE, '..', '..', 'server', 'assets', 'music');
const OUT = join(HERE, '..', 'src', 'assets', 'music.ts');
const b64 = readFileSync(join(SRC, 'menu.m4a')).toString('base64');
writeFileSync(
  OUT,
  `// Generated by scripts/bundle-music.mjs from server/assets/music (AAC-LC in fragmented MP4, CC0). Do not edit.\n` +
    `export const MUSIC = '${b64}';\n`,
);
console.log(`wrote ${OUT}`);
